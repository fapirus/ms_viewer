use std::fs;
use std::io::Write;

use format_xlsx::parse_frozen_panes;
use format_xlsx::parse_xlsx;
use format_xlsx::XlsxActivePane;
use format_xlsx::XlsxFrozenPaneState;
use tempfile::tempdir;
use viewer_core::archive::OoxmlArchive;
use viewer_core::ViewerError;
use zip::write::SimpleFileOptions;

fn create_zip(path: &std::path::Path, entries: &[(&str, &[u8])]) {
    let file = fs::File::create(path).expect("zip file should be created");
    let mut writer = zip::ZipWriter::new(file);

    for (name, bytes) in entries {
        writer
            .start_file(name, SimpleFileOptions::default())
            .expect("entry should start");
        writer.write_all(bytes).expect("entry bytes should write");
    }

    writer.finish().expect("zip should finish");
}

#[test]
fn parses_frozen_rows_and_columns() {
    let dir = tempdir().expect("tempdir should exist");
    let path = dir.path().join("frozen-panes.xlsx");
    create_zip(
        &path,
        &[
            (
                "_rels/.rels",
                br#"
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>
"#,
            ),
            (
                "xl/workbook.xml",
                br#"
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"
          xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="Sheet1" sheetId="1" r:id="rIdSheet1"/>
  </sheets>
</workbook>
"#,
            ),
            (
                "xl/_rels/workbook.xml.rels",
                br#"
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rIdSheet1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>
"#,
            ),
            (
                "xl/worksheets/sheet1.xml",
                br#"
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetViews>
    <sheetView workbookViewId="0">
      <pane xSplit="2" ySplit="1" topLeftCell="C2" activePane="bottomRight" state="frozen"/>
    </sheetView>
  </sheetViews>
  <sheetData/>
</worksheet>
"#,
            ),
        ],
    );

    let archive = OoxmlArchive::open_path(&path).expect("archive should open");
    let workbook = parse_xlsx(&archive).expect("xlsx should parse");
    let frozen_panes = parse_frozen_panes(&archive, &workbook).expect("frozen panes");

    assert_eq!(frozen_panes.len(), 1);
    let pane = frozen_panes[0]
        .pane
        .as_ref()
        .expect("frozen pane should exist");
    assert_eq!(frozen_panes[0].part_name, "xl/worksheets/sheet1.xml");
    assert_eq!(pane.x_split, Some(2.0));
    assert_eq!(pane.y_split, Some(1.0));
    assert_eq!(pane.top_left_cell.as_deref(), Some("C2"));
    assert_eq!(pane.state, XlsxFrozenPaneState::Frozen);
    assert_eq!(pane.active_pane, Some(XlsxActivePane::BottomRight));
}

